"""Render real Qt widgets with synthetic examples; no network or user data."""
import os
os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')
import tempfile
from pathlib import Path
from PyQt5 import QtWidgets as W
from docx import Document
from scholarstyle.gui import Window

OUTPUT = Path(__file__).resolve().parents[1] / 'docs' / 'screenshots'
OUTPUT.mkdir(parents=True, exist_ok=True)
app = W.QApplication.instance() or W.QApplication([])
app.setStyle('Fusion')
with tempfile.TemporaryDirectory(prefix='scholarstyle-docs-') as directory:
    root = Path(directory)
    window = Window(root)
    window.language_box.setCurrentIndex(window.language_box.findData('en'))
    window.theme_box.setCurrentIndex(window.theme_box.findData('light'))
    examples = [
        ('Example 01 - Reporting experimental observations', 'We examined neuronal activity across twelve cultures under controlled conditions. Recordings were collected at consistent intervals to characterize temporal changes in network activity. These observations suggest that activity patterns vary across cultures, although the underlying mechanisms remain unresolved.'),
        ('Example 02 - Writing cautious interpretations', 'The observed differences may reflect variation in the experimental conditions. We therefore interpret these findings cautiously and distinguish measured effects from possible explanations. Further experiments are needed to evaluate whether the same patterns occur in independent samples.'),
        ('Example 03 - Structuring a methods paragraph', 'We quantified network activity using a predefined analysis procedure. Each recording was processed with the same parameters to maintain consistency across experimental groups. Summary statistics were calculated for individual cultures before comparisons were performed across groups.'),
    ]
    for title, prose in examples:
        doc = Document(); doc.add_heading(title, 0); doc.add_paragraph(prose)
        path = root / (title + '.docx'); doc.save(path)
        window.library.import_file(path, title=title, source='Synthetic documentation example')
    ids = [p['id'] for p in window.library.papers()]
    window.library.train(ids, 'Documentation demo', None, lambda _: None, lambda: False)
    window.refresh()
    window.frozen_path.setText('demo-data/frozen_style.sqlite')
    window.resize(1440, 1100)
    window.show(); app.processEvents()
    window.grab().save(str(OUTPUT / 'library.png'))
    window.paper_sources.setCurrentIndex(1)
    window.author_name.setText('Search by author name, affiliation or ORCID')
    app.processEvents(); window.grab().save(str(OUTPUT / 'discovery.png'))
    window.tabs.setCurrentIndex(1)
    original = 'We looked at neuronal activity in 12 cultures. We used the same recording settings for all cultures. The results suggest that network activity may vary between cultures.'
    revised = 'We examined neuronal activity in 12 cultures using consistent recording settings. The results suggest that network activity may vary across cultures.'
    window.draft.setPlainText(original)
    window.instruction.setText('Improve sentence structure; preserve numbers, meaning and uncertainty.')
    record = {'index': 0, 'original': original, 'revised': revised,
              'explanation': 'Illustrative edit: combines the methods sentences and uses more precise scientific wording. This example was written for the documentation, not generated by a model.',
              'warnings': [], 'model_warnings': [], 'accepted': False,
              'references': [{'title': examples[0][0], 'source': 'Synthetic documentation example', 'excerpt': examples[0][1]}]}
    window.session = {'complete': True, 'records': [record]}
    window.add_record(record)
    app.processEvents(); window.grab().save(str(OUTPUT / 'draft-studio.png'))
    window.theme_box.setCurrentIndex(window.theme_box.findData('dark'))
    app.processEvents(); window.grab().save(str(OUTPUT / 'draft-dark.png'))
    for label in window.settings_dialog.findChildren(W.QLabel):
        if str(root) in label.text():
            label.setText(label.text().replace(str(root), 'demo-data'))
    window.settings_dialog.show(); app.processEvents()
    window.settings_dialog.grab().save(str(OUTPUT / 'model-settings.png'))
    window.settings_dialog.close(); window.close()
print('Saved five screenshots to', OUTPUT)
